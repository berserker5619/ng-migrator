import { randomBytes } from 'node:crypto';
import { mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';

/** Error codes caused by antivirus, indexers or editors briefly holding a file (mostly Windows). */
const TRANSIENT_CODES = new Set(['EBUSY', 'EPERM', 'EACCES', 'ENOTEMPTY', 'EMFILE', 'ENFILE']);

export interface RetryOptions {
  retries?: number;
  baseDelayMs?: number;
}

export function isTransientFsError(err: unknown): boolean {
  const code = (err as NodeJS.ErrnoException | undefined)?.code;
  return code !== undefined && TRANSIENT_CODES.has(code);
}

/** Retry an fs operation with exponential backoff on transient lock errors. */
export async function withFsRetry<T>(fn: () => Promise<T>, options: RetryOptions = {}): Promise<T> {
  const retries = options.retries ?? 6;
  const base = options.baseDelayMs ?? 25;
  for (let attempt = 0; ; attempt++) {
    try {
      return await fn();
    } catch (err) {
      if (attempt >= retries || !isTransientFsError(err)) throw err;
      await new Promise((resolve) => setTimeout(resolve, base * 2 ** attempt));
    }
  }
}

/**
 * Write a file atomically: write a temporary file in the same directory, then
 * rename over the target (with retry). Readers never see a half-written file.
 */
export async function atomicWrite(file: string, data: string | Uint8Array, options: RetryOptions = {}): Promise<void> {
  const dir = path.dirname(file);
  await mkdir(dir, { recursive: true });
  const tmp = path.join(dir, `.${path.basename(file)}.${process.pid}.${randomBytes(4).toString('hex')}.tmp`);
  try {
    await writeFile(tmp, data, { flag: 'wx' });
    await withFsRetry(() => rename(tmp, file), options);
  } catch (err) {
    await rm(tmp, { force: true }).catch(() => undefined);
    throw err;
  }
}

/** Delete a file or directory tree, retrying on transient lock errors. Missing paths are fine. */
export async function removeWithRetry(target: string, options: RetryOptions = {}): Promise<void> {
  await withFsRetry(() => rm(target, { recursive: true, force: true, maxRetries: 3, retryDelay: 50 }), options);
}

export async function pathExists(target: string): Promise<boolean> {
  try {
    await readFile(target);
    return true;
  } catch (err) {
    const code = (err as NodeJS.ErrnoException).code;
    if (code === 'ENOENT' || code === 'ENOTDIR') return false;
    if (code === 'EISDIR') return true;
    throw err;
  }
}

/** Read JSON, returning `undefined` if the file does not exist. Strips a UTF-8 BOM. */
export async function readJsonIfExists<T = unknown>(file: string): Promise<T | undefined> {
  let raw: string;
  try {
    raw = await readFile(file, 'utf8');
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === 'ENOENT') return undefined;
    throw err;
  }
  return JSON.parse(raw.replace(/^\uFEFF/, '')) as T;
}

/** Write JSON generated by the tool: 2-space indent, LF, trailing newline, atomic. */
export async function writeJsonAtomic(file: string, value: unknown): Promise<void> {
  await atomicWrite(file, `${JSON.stringify(value, null, 2)}\n`);
}

